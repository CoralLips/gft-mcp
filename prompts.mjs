// 与 thinkingMapService.ts 的 SHARED_RULES 保持逐字一致
export const SHARED_RULES = `# node 怎么抽

- 一个 node = 一个独立的认知单元：判断、结论、洞察、关键问题
- title：≤16 字的锐利短句，不是主题词。好：「内容导航比过程导航有用」；坏：「关于导航的讨论」
- title 是图上唯一直接可见的内容——必须一句自明，读者不点开也能懂
- body：一句支撑说明（≤40 字）——这个判断**为什么成立**、或它来自什么语境；只在用户点开详情时显示、不占图面。除非 title 已完全自明，尽量给
- 狠合并：说同一件事的不同表述合成一个 node；丢弃寒暄、过程语句（"我又想了想"）、岔开的话题
- 不发明：只抽用户真说了的，不替他补观点
- **问题节点**：用户提出的问题，按「是否被充分解决」定形态——
  - 充分解决（回答直接回应了核心，用户接受并顺着结论继续走）→ 只把结论写成陈述句节点，问题不单独立节点
  - **未充分解决**（回答跑题 / 只答了一半 / 含糊其辞 / 问题里明显还有没被覆盖的部分、或用户仍在追问纠结）→ 保留为问句节点：title 就是那个问题（≤16 字，以"？"结尾）
  - 修辞性反问不算问题；宁缺毋滥
- **按思考发展的先后顺序输出 node**——先出现的判断先输出，输出顺序就是图的时间骨架

# edge 怎么连（骨架=时序，一条线只有一个读法）

- 一条边 = 承接：from→to 表示"to 是顺着 from 来的"
- **只许顺着时间连**：to 必须比 from 晚出现，绝不允许指回更早的节点
- 一个节点引出多条边 = 思考从这里分头（分叉，允许）
- 多条边汇入同一个节点 = 合并：仅当它**同时用到了那几条线的结论**才成立；砍掉其中一条来源线它还讲得通，就别连——话题相似不算合并
- **不分类型**：只连一条朴素线，别纠结是哪种关系、别上类型
- 只连真实存在的承接；不确定就不连；**宁可少连，绝不为了图好看硬连**；孤立节点允许

# 转折（让图讲得出思路的走向）

- **转折边**：新话头是从前面的路**拐过来**的——前面聊到头/走不通，用户转向另一个方向（"这个不行，那我们换个思路""其实我还想过另一件事"）→ 给那条承接边加 turn：<edge from="n2" to="n5" turn="true"/>。turn 表示"从这拐过来的"，不是顺着深化。真正毫无关系的全新话题不连任何边。

# 输入形态

输入可能是一段笔记，也可能是「用户与 AI 的对话记录」。如果是对话记录：
- 以**用户的判断**为主线抽取；
- AI 说的只有被用户认可、采纳或构成关键转折时才抽；
- 忽略寒暄、AI 的铺陈和未被接住的建议；
- 输入末尾若附有「用户发言清单」：那是用户原话的完整索引，抽取以它为主线——他的核心提问别漏，但清单条目≠节点，铺垫和闲聊照删。`;

/** 单次新增节点数硬上限（对齐 thinkingMapService 的 NODE_CAP_MAX） */
export const NODE_CAP = 12;

/**
 * 增量抽取指令 —— 对齐 buildUpdatePrompt。
 * 差别只有一处：GFT 内部把「新对话」放在 user message 里，这里由 agent 自己持有对话，
 * 所以改成"从你和用户这场对话里找"。规则本身一字不改。
 * watermarks = [{id, cursor}] —— 同一张图可能被多个 session 喂,各有各的进度,认自己那条。
 */
export function buildUpdateInstruction(serializedMap, watermarks) {
  const list = Array.isArray(watermarks) ? watermarks : (watermarks ? [{ id: 'default', cursor: watermarks }] : []);
  const since = list.length
    ? `\n# 各方抽取进度（认你自己那条——id 是提交时自报的 agent_id；不是你的一律无视）\n\n${
        list.map(w => `- [${w.id}] ${w.cursor}`).join('\n')
      }\n\n你的进度若在列：只看那之后的对话；不在列：这张图还没吃过你这条线，本场从头看起。`
    : '\n# 各方抽取进度\n\n（这张图还没吃过外部对话，本场从头看起）';

  return `# 把这场对话里的新判断补进用户的思维脉络

下面是「上一版思维导航图」——它已经归用户了，你**不能改**。
你只做一件事：从**你和用户的这场对话**里找出图上还没有的新判断，以增量补进图。
${since}

# 上一版图（只读上下文）

${serializedMap}

# 你只许输出两种标签（每行一个，无其他文字）

<node id="m1" title="..." body="..."/>
<edge from="n2" to="m1"/>

- 新节点：id 用 m1、m2… 按出现先后顺序编号
- 新边：from 可以是旧节点（nX）或更早的新节点（mX）；**to 只能是新节点**——不许改写历史
- 想标转折用 <edge from="n2" to="m1" turn="true"/>

# 铁律

- 旧节点、旧边一律不重新输出、不修改、不删除
- 只抽**用户真说了的**新判断；你自己的分析除非用户明确接住了，否则不上图
- 这场对话若没有值得记的新东西，只输出 <noop/>
- 单次新增最多 ${NODE_CAP} 个 node；图上已有的判断不重复产

${SHARED_RULES}

# 抽完怎么办

把上面的标签原样传给 submit_map_update 工具的 tags 参数：
- cursor 写清本次抽到哪（例如"2026-08-05 关于 MCP 外接的讨论，至第 40 轮"），下次好接着走
- agent_id 传你这条线的稳定标识（工作目录名或话题名，跨重启不变）——水位按它分开记，别的 session 才不会踩你的进度`;
}

